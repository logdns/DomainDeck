import assert from 'node:assert/strict';
import { once } from 'node:events';
import { mkdirSync, writeFileSync } from 'node:fs';
import { randomBytes } from 'node:crypto';
import { join } from 'node:path';
import { openDatabase } from '../src/database.js';
import { createAccount } from '../src/accounts.js';
import { createApp } from '../src/server.js';
import { seedDemo, demoTransport } from '../src/demo.js';
import { saveSetting } from '../src/store.js';

const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || '/tools/node_modules/playwright/index.mjs');
const output = process.env.BROWSER_OUTPUT || '/scratch/browser';
mkdirSync(output, { recursive: true });
const database = openDatabase(':memory:');
await createAccount(database, { username: 'admin', password: 'fixture-password' });
await createAccount(database, { username: 'viewer', password: 'fixture-password' });
database.prepare("UPDATE users SET role='viewer' WHERE username='viewer'").run();
const key = randomBytes(32);
seedDemo(database, key);
saveSetting(database, 'safety', { billingEnabled: true, confirmWrites: true });
saveSetting(database, 'contacts', { registrant: 'fixture-contact' });
const server = createApp(database, { key, transport: demoTransport, version: '3.0.0-beta.6', demo: true });
server.listen(0, '127.0.0.1');
await once(server, 'listening');
const base = `http://127.0.0.1:${server.address().port}`;
const browser = await chromium.launch({ executablePath: '/usr/bin/chromium', headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage', '--disable-background-networking'] });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
const page = await context.newPage();
const errors = [];
const failures = [];
page.on('pageerror', (error) => errors.push(error.message));
page.on('response', (response) => { if (response.url().startsWith(base) && response.status() >= 400) failures.push(`${response.status()} ${response.url()}`); });
const login = async (username) => {
  await page.goto(`${base}/#/auth/login`);
  await page.getByPlaceholder('请输入用户名', { exact: true }).fill(username);
  await page.getByPlaceholder('请输入密码', { exact: true }).fill('fixture-password');
  await page.getByRole('button', { name: 'login', exact: true }).click();
  await page.waitForURL('**/#/overview', { timeout: 15000 });
  await page.locator('.deck-heading:visible').last().waitFor();
};
const visit = async (path) => {
  await page.goto(`${base}/#${path}`);
  await page.locator('.deck-heading:visible').last().waitFor();
  await page.waitForLoadState('networkidle');
  assert.ok((await page.locator('.deck-heading:visible').last().textContent()).trim(), path);
  console.log(`Browser page OK: ${path}`);
};
try {
  await page.goto(base);
  await page.getByPlaceholder('请输入用户名', { exact: true }).waitFor();
  await page.screenshot({ path: join(output, 'login.png'), fullPage: true });
  await login('admin');
  await page.screenshot({ path: join(output, 'overview.png'), fullPage: true });
  for (const path of ['/domains', '/register', '/transfer', '/dns', '/providers', '/payments', '/notifications', '/settings', '/system/accounts', '/system/roles']) await visit(path);
  await visit('/domains');
  assert.ok((await page.locator('body').textContent()).includes('spaceship.example'));
  await page.screenshot({ path: join(output, 'domains.png'), fullPage: true });
  await page.getByRole('button', { name: '登记 / 导入资产', exact: true }).click();
  const assetDialog = page.getByRole('dialog');
  await assetDialog.getByPlaceholder('域名，例如 example.com', { exact: true }).fill('manual-fixture.example');
  await assetDialog.getByPlaceholder('到期日期（可选），例如 2030-01-01').fill('2030-01-01');
  await assetDialog.getByRole('button', { name: '保存资产', exact: true }).click();
  await assetDialog.waitFor({ state: 'hidden' });
  assert.equal(database.prepare('SELECT name FROM domains WHERE name=?').get('manual-fixture.example').name, 'manual-fixture.example');
  await visit('/register');
  await page.getByPlaceholder('输入要查询的域名，例如 yourname.com').fill('purchase-fixture.example');
  await page.getByRole('button', { name: /^查\s*询$/ }).click();
  await page.getByRole('row').filter({ hasText: 'Demo spaceship' }).getByRole('button', { name: /^注\s*册$/ }).click();
  const registration = page.getByRole('dialog').filter({ hasText: '注册域名' });
  await registration.getByRole('button', { name: '确认注册', exact: true }).click();
  await page.getByRole('button', { name: /^取\s*消$/ }).last().click();
  assert.equal(database.prepare('SELECT count(*) AS count FROM orders').get().count, 0);
  await registration.getByRole('button', { name: '确认注册', exact: true }).click();
  await page.getByRole('button', { name: '确认扣款并提交', exact: true }).click();
  await registration.waitFor({ state: 'hidden' });
  assert.equal(database.prepare('SELECT status FROM orders').get().status, 'pending');
  await visit('/providers');
  assert.ok((await page.locator('body').textContent()).includes('Porkbun'));
  const syncResponse = page.waitForResponse((response) => response.url().includes('/api/vben/connections/') && response.url().endsWith('/sync'));
  await page.getByRole('button', { name: '同步域名', exact: true }).first().click();
  assert.equal((await syncResponse).status(), 200);
  await visit('/payments');
  await page.getByRole('button', { name: '手工登记支付方式', exact: true }).first().click();
  const paymentDialog = page.getByRole('dialog');
  await paymentDialog.getByPlaceholder('例如：支付宝 · 主账号').fill('Browser payment fixture');
  await paymentDialog.getByPlaceholder('chck@example.com').fill('fixture@example.test');
  await paymentDialog.getByRole('button', { name: /^保\s*存$/ }).click();
  await paymentDialog.waitFor({ state: 'hidden' });
  assert.equal(database.prepare('SELECT name FROM payments').get().name, 'Browser payment fixture');
  await page.reload();
  await page.getByText('Browser payment fixture', { exact: true }).first().waitFor();
  await visit('/dns');
  await page.screenshot({ path: join(output, 'dns.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await visit('/overview');
  await page.screenshot({ path: join(output, 'mobile.png'), fullPage: true });
  await context.clearCookies();
  await page.evaluate(() => { localStorage.clear(); sessionStorage.clear(); });
  await page.goto('about:blank');
  await page.setViewportSize({ width: 1440, height: 1000 });
  await login('viewer');
  await visit('/domains');
  assert.equal(await page.getByRole('button', { name: '同步域名', exact: true }).count(), 0);
  await page.goto(`${base}/#/payments`);
  await page.waitForURL('**/#/access-denied');
  assert.deepEqual(errors, [], 'Browser runtime errors');
  assert.deepEqual(failures, [], 'Unexpected HTTP failures');
  writeFileSync(join(output, 'result.json'), JSON.stringify({ ok: true, pages: 11, checks: ['login', 'menu-permissions', 'all-pages', 'asset-persistence', 'purchase-cancel', 'purchase-confirm', 'registrar-sync', 'payment-persistence', 'mobile', 'viewer-route-guard'], errors, failures }, null, 2));
  console.log('Vben + Node + SQLite browser integration passed');
} catch (error) {
  console.error(JSON.stringify({ message: error.message, url: page.url(), text: (await page.locator('body').textContent()).slice(0, 1800), errors, failures }));
  await page.screenshot({ path: join(output, 'failure.png'), fullPage: true }).catch(() => {});
  throw error;
} finally {
  await browser.close();
  await new Promise((resolve) => server.close(resolve));
  database.close();
}
